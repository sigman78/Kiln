// examples/sokol/main.cpp — kiln-sokol: one model and a cube sky through sokol_gfx, with sokol_app
// owning the main loop (docs/design/integration-examples.md). kiln lives in the app callbacks: create()
// in init, pump() (which runs the adapter's flush) and the draw in frame, destroy() in cleanup.
// Meshes are cooked with VertexProfile::Float. The steps a host takes are numbered.
